def nip_group(fill, with_rod=True):
    t=f'  <group android:translateX="{L["tx"]:.3f}" android:translateY="{L["ty"]:.3f}" android:scaleX="{L["scale"]:.4f}" android:scaleY="{L["scale"]:.4f}">\n'
