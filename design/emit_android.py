# --- synthesized typewriter sounds ---
SR=44100
def save(name,samples):
    w=wave.open(f'{R}/raw/{name}.wav','wb'); w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes(b''.join(struct.pack('<h',max(-32767,min(32767,int(s*32767)))) for s in samples)); w.close()
random.seed(7)
def key(seed,dur=0.06):
    random.seed(seed); n=int(SR*dur); out=[]; lp=0
    for i in range(n):
        t=i/SR; env=math.exp(-t*90)
        noise=random.uniform(-1,1); lp=lp*0.55+noise*0.45
        thunk=math.sin(2*math.pi*180*t)*math.exp(-t*60)*0.5
        out.append((lp*0.8+thunk)*env*0.8)
    return out
save('key_a',key(1)); save('key_b',key(2)); save('key_c',key(3))
def ding():
    n=int(SR*1.2); return [ (math.sin(2*math.pi*2093*i/SR)*0.5+math.sin(2*math.pi*4186*i/SR)*0.2+math.sin(2*math.pi*3140*i/SR)*0.12)*math.exp(-i/SR*3.2)*0.6 for i in range(n)]
save('ding',ding())
def ret():
    random.seed(9); n=int(SR*0.45); out=[]; lp=0
    for i in range(n):
        t=i/SR; ratchet=1.0 if (int(t*38)%2==0 and t<0.32) else 0.25
        lp=lp*0.7+random.uniform(-1,1)*0.3
        env=(0.5 if t<0.32 else math.exp(-(t-0.32)*40)*1.4)
        out.append(lp*ratchet*env*0.7)
    return out
save('carriage_return',ret())
