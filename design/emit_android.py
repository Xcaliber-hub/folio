    for k in ks: t+=f'    <path android:fillColor="{fill}" android:pathData="{P[k]}"/>\n'
    t+=f'    <path android:fillColor="{fill}" android:fillType="evenOdd" android:pathData="{P["PILL"]}"/>\n  </group>\n'
    return t
